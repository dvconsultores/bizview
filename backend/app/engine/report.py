# Both renderers (web and PDF) read one payload, so the summary sentence and the table totals are
# produced here, once, with the same helpers the rest of the product uses for metric values.

def _pdf_fmt(value, kind: str, cur: str) -> str:
    """Metric value formatting of the payload's own renderer (one implementation, feature 017)."""
    from app.reports.pdf import fmt
    return fmt(value, kind, cur)


def _month_name(month: int) -> str:
    months = t("summary.months").split(",")
    return months[month - 1].strip() if 0 < month <= len(months) else str(month)


def _day(d: date) -> str:
    return str(d.day)


def _range_text(r: periods.Range) -> str:
    """The period as a phrase: "del 1 al 30 de septiembre de 2026" (es), "from ... to ..." (en)."""
    if r.start == r.end:
        return t("summary.range_day", day=_day(r.start), month=_month_name(r.start.month),
                 year=str(r.start.year))
    if (r.start.year, r.start.month) == (r.end.year, r.end.month):
        return t("summary.range_same_month", from_day=_day(r.start), to_day=_day(r.end),
                 month=_month_name(r.start.month), year=str(r.start.year))
    if r.start.year == r.end.year:
        return t("summary.range_same_year", from_day=_day(r.start),
                 from_month=_month_name(r.start.month), to_day=_day(r.end),
                 to_month=_month_name(r.end.month), year=str(r.start.year))
    return t("summary.range", from_day=_day(r.start), from_month=_month_name(r.start.month),
             from_year=str(r.start.year), to_day=_day(r.end), to_month=_month_name(r.end.month),
             to_year=str(r.end.year))


def _date_text(bucket: str) -> str:
    """A bucket date as the renderer writes dates (same helper the PDF uses)."""
    from app.reports.pdf import fmt_date
    try:
        return fmt_date(bucket)
    except (TypeError, ValueError):
        return str(bucket)


def _bucket_day(bucket: str) -> str | None:
    try:
        return str(date.fromisoformat(str(bucket)).day)
    except ValueError:
        return None


def _list_text(parts: list[str]) -> str:
    if len(parts) < 2:
        return "".join(parts)
    return t("summary.list_sep").join(parts[:-1]) + t("summary.list_and") + parts[-1]


def _extreme_word(metric: dict | None) -> str:
    """The extreme that matters for the metric: its worst side (`better` semantics)."""
    return t("summary.extreme.lower" if (metric or {}).get("better") == "lower"
             else "summary.extreme.higher")


def view_summary(ctx: Context, vdef: dict, view: dict, sel: periods.Selection) -> str:
    """One sentence describing the view: its type, labels, grain and the extremes of the data.

    It is the web chart's `aria-label` and the PDF chart's caption, so the words are built here
    and nowhere else (accessibility edge case of the specification)."""
    cur = currency(ctx)
    rng = _range_text(sel.current)
    if view.get("type") == "kpis":
        items = [i for i in view.get("items") or [] if i.get("value") is not None]
        if not items:
            return t("summary.empty", range=rng)
        return t("summary.kpis", range=rng, items=_list_text([
            t("summary.kpi_item", label=localized(i, "label") or i["metric"],
              value=_pdf_fmt(i["value"], i.get("format", "number"), cur)) for i in items]))
    if view.get("type") == "trend":
        mid = view.get("metric") or ""
        points = [(p["bucket"], p["value"]) for p in view.get("points") or []
                  if p.get("value") is not None]
        if not points:
            return t("summary.empty", range=rng)
        metric = ctx.metrics.get(mid) or {}
        bucket, value = (min if metric.get("better") == "lower" else max)(
            points, key=lambda p: p[1])
        grain = view.get("grain") if view.get("grain") in ("day", "week", "month") else "day"
        day = _bucket_day(bucket) if grain == "day" else None
        when = (t("summary.when_day", day=day) if day
                else t("summary.when_date", date=_date_text(bucket)))
        return t("summary.trend", label=localized(view, "label") or mid,
                 grain=t(f"summary.grain.{grain}"), range=rng, extreme=_extreme_word(metric),
                 value=_pdf_fmt(value, view.get("format", "number"), cur), when=when)
    if view.get("type") == "ranking":
        items = [i for i in view.get("items") or [] if i.get("value") is not None]
        if not items:
            return t("summary.empty", range=rng)
        top = items[0]
        return t("summary.ranking", label=localized(view, "label") or view.get("metric", ""),
                 dimension=localized(view, "dimension_label") or view.get("dimension", ""),
                 range=rng, top=str(_json_key(top["key"]) if top["key"] is not None else "—"),
                 value=_pdf_fmt(top["value"], view.get("format", "number"), cur),
                 share=_pdf_fmt(top.get("share"), "percent", cur))
    cols = view.get("columns") or []
    rows = view.get("rows") or []
    title = (localized(view, "title")
             or (localized(cols[0], "label") if cols else None) or t("pdf.detail"))
    if view.get("type") == "table":
        if not rows:
            return t("summary.empty", range=rng)
        count = tn("summary.rows", len(rows))
        metric_cols = [c for c in cols if c.get("kind") == "metric"]
        values = [r for r in rows if metric_cols and r.get(metric_cols[0]["id"]) is not None]
        if not values:
            return t("summary.table_rows", title=title, range=rng, rows=count)
        col = metric_cols[0]
        metric = ctx.metrics.get(col["id"]) or {}
        row = (min if metric.get("better") == "lower" else max)(
            values, key=lambda r: r[col["id"]])
        dim_cols = [c for c in cols if c.get("kind") != "metric"]
        top = (str(row.get(dim_cols[0]["id"])) if row.get(dim_cols[0]["id"]) is not None
               else "—") if dim_cols else "—"
        return t("summary.table", title=title, range=rng, rows=count,
                 extreme=_extreme_word(metric),
                 value=_pdf_fmt(row[col["id"]], col.get("format", "number"), cur), top=top)
    # Only the four catalogued view types are executed (VIEWS); anything else names itself.
    return t("summary.table_rows", title=title, range=rng,
             rows=tn("summary.rows", len(rows)))


def _view_metrics(vdef: dict) -> list[str]:
    """Los ids de las métricas que muestra la vista, sea cual sea su tipo.

    Las vistas `kpis` y `table` declaran `metrics`; `trend` y `ranking`, `metric`.
    """
    declared = vdef.get("metrics")
    if isinstance(declared, list):
        return [m for m in declared if isinstance(m, str)]
    metric = vdef.get("metric")
    return [metric] if isinstance(metric, str) else []


def _totals_views(ctx: Context) -> set[str]:
    """View ids that a layout marks with `totals: true`, in either layout half."""
    layout = ctx.definition.get("layout") or {}
    parts = list((layout.get("web") or {}).get("components") or []) + list(
        (layout.get("pdf") or {}).get("blocks") or [])
    return {p["view"] for p in parts
            if isinstance(p, dict) and p.get("totals") is True and isinstance(p.get("view"), str)}


def _view_totals(ctx: Context, vdef: dict, sel: periods.Selection, filters: dict, tz: str,
                 *, session=None) -> dict:
    """Value per metric of the view, aggregated by the metric itself (never by summing rows)."""
    mids = [m for m in _view_metrics(vdef) if m in ctx.metrics]
    if not mids:
        return {}
    row = aggregate(ctx, mids, sel.current, filters, tz, session=session)[0]
    return {m: row.get(m) for m in mids}


def _view_facts(ctx: Context, vdefs: list[dict], views: list[dict], sel: periods.Selection,
                filters: dict, tz: str, *, session=None) -> None:
    """Add the derived facts to each payload view (feature 026, data-model §7).

    The summary travels in both languages because the payload is cached per selection, not per
    request language (`localized()` picks `summary_en` for English, like every other text)."""
    wanted = _totals_views(ctx)
    for vdef, view in zip(vdefs, views, strict=True):
        if view.get("error"):
            continue
        with use_locale("es"):
            view["summary"] = view_summary(ctx, vdef, view, sel)
        with use_locale("en"):
            view["summary_en"] = view_summary(ctx, vdef, view, sel)
        if vdef.get("id") in wanted:
            view["totals"] = _view_totals(ctx, vdef, sel, filters, tz, session=session)


