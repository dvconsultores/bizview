"""Generic report engine (feature 005, research R5, FR-013 to FR-016).

A report definition (validated `report.yaml` in the active workspace version) declares datasets
(`uses`), joins, a date column, metric and dimension expressions, and views. The engine builds
one read-only query per view and period over the engine-owned dataset tables:

- expressions are re-checked with the shared allow-list and re-generated by the SQL parser with
  every identifier quoted; aliases map only to the report's declared datasets;
- values (dates, filter values) are SQL literals composed by psycopg, never string-formatted;
- queries run in a read-only transaction with a statement time limit.

Formulas (`net_sales / orders`) are evaluated here over the aggregated values; division by zero
gives null.
"""
