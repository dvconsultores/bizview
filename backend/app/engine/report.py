def selection(ctx: Context, params: Iterable[tuple[str, str]] | Mapping[str, str],
              today: date) -> tuple[periods.Selection, dict[str, list[str]]]:
    pairs = list(params.items() if isinstance(params, Mapping) else params)
    scalar_params: dict[str, str] = {}
    for key, value in pairs:
        scalar_params[key] = value

    d = ctx.definition
    conf_p, conf_c = d.get("periods") or {}, d.get("compare") or {}
    period = scalar_params.get("period") or conf_p.get("default") or "mtd"
    allowed = conf_p.get("allowed") or list(periods.PRESETS)
    if period not in allowed:
        raise ReportError(M("report.period_not_allowed"))
    compare = scalar_params.get("compare") or conf_c.get("default") or "previous_period"
    if compare not in (conf_c.get("allowed") or list(periods.COMPARISONS)) and compare != "none":
        raise ReportError(M("report.compare_not_allowed"))
    custom = None
    if period == "custom":
        try:
            custom = (date.fromisoformat(scalar_params.get("from") or ""),
                      date.fromisoformat(scalar_params.get("to") or ""))
        except ValueError:
            raise ReportError(M("report.invalid_dates")) from None
    try:
        sel = periods.resolve(period, compare, today, custom=custom)
    except periods.PeriodError as e:
        raise ReportError(e.message) from None

    collected: dict[str, set[str]] = {dim: set() for dim in d.get("filters") or []}
    for key, value in pairs:
        if not key.startswith("filter."):
            continue
        dim = key[len("filter."):]
        if dim not in collected or value in (None, ""):
            continue
        collected[dim].add(str(value)[:200])

    filters: dict[str, list[str]] = {}
    for dim in d.get("filters") or []:
        values = sorted(collected[dim])
        if not values:
            continue
        if len(values) > MAX_FILTER_VALUES:
            label = localized(ctx.dimensions[dim], "label") or dim
            raise ReportError(
                M("report.too_many_filter_values", label=label, max=MAX_FILTER_VALUES),
                422, "too_many_values")
        filters[dim] = values
    return sel, filters


def _epoch() -> float:
    return time.time()


def direct_version(ctx: Context) -> str:
    bucket = int(_epoch() // ctx.direct.cache_seconds)
    return f"v{ctx.version.id}-d{bucket}"


def data_version(db, ctx: Context) -> tuple[str, datetime | None]:
    """Changes whenever a used integration loads new data or another version is applied."""
    if ctx.direct is not None:
        return direct_version(ctx), None
    last_id, updated = db.execute(
        select(func.max(IntegrationRun.id), func.max(IntegrationRun.finished_at))
        .where(IntegrationRun.integration_id.in_(ctx.integrations),
               IntegrationRun.status == "succeeded")).one()
    return f"v{ctx.version.id}-r{last_id or 0}", updated


def data_version_and_cached(db, ctx: Context, selection_key: str,
                            kind: str) -> tuple[str, datetime | None, dict | None]:
    """data_version() and the cached payload for that version in one round trip."""
    if ctx.direct is not None:
        version = direct_version(ctx)
        payload = db.scalar(
            select(ReportCache.payload)
            .where(ReportCache.report_id == ctx.report_id,
                   ReportCache.selection_hash == selection_key,
                   ReportCache.kind == kind,
                   ReportCache.data_version == version))
        return version, None, payload
    runs = (select(func.max(IntegrationRun.id).label("rid"),
                   func.max(IntegrationRun.finished_at).label("upd"))
            .where(IntegrationRun.integration_id.in_(ctx.integrations),
                   IntegrationRun.status == "succeeded")
            .subquery())
    version = func.concat(f"v{ctx.version.id}-r", func.coalesce(runs.c.rid, 0))
    rid, updated, payload = db.execute(
        select(runs.c.rid, runs.c.upd, ReportCache.payload)
        .select_from(runs)
        .outerjoin(ReportCache, (ReportCache.report_id == ctx.report_id)
                   & (ReportCache.selection_hash == selection_key)
                   & (ReportCache.kind == kind)
                   & (ReportCache.data_version == version))).one()
    return f"v{ctx.version.id}-r{rid or 0}", updated, payload


def selection_hash(sel: periods.Selection, filters: dict[str, list[str]],
                   extra: str = "") -> str:
    raw = json.dumps({"s": sel.to_json(), "f": filters, "x": extra}, sort_keys=True)
    return hashlib.sha256(raw.encode()).hexdigest()[:32]


