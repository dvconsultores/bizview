    """A report bound to the active version: aliases → tables and column types."""
    report_id: str
    definition: dict
    version: WorkspaceVersion
    tables: dict[str, tuple[str, str]]                 # alias → (schema, table)
    columns: dict[str, dict[str, dict]]                 # alias → column contracts
    integrations: list[str]
    runner: Runner = BI_RUNNER
