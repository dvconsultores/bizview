def _build_direct_context(report_id: str, d: dict, version) -> Context:
    cfg = d["direct"]
    source = cfg["source"].strip()
    bi = source.lower() == "bi"
    label = source  # raw id ("bi" or a source name); clients render "bi" in their language

    logical, tables, columns = {}, {}, {}
    for alias, tbl in cfg["tables"].items():
        schema, _, table = tbl["table"].partition(".")
        msg = direct.refusal(schema, table, bi=bi)
        if msg:
            raise ReportError(msg, 409, "direct_product_table")
        logical[alias] = (schema, table)
        tables[alias] = (direct.physical_schema(schema), table)
        columns[alias] = tbl["columns"]

    timeout = cfg.get("timeout_seconds") or 15
    runner = direct.DirectRunner(
        source,
        report_id=report_id,
        timeout_seconds=timeout,
        tables=logical,
        columns=columns,
        version_key=getattr(version, "id", None),
    )
    spec = DirectSpec(
        source=source,
        label=label,
        cache_seconds=cfg.get("cache_seconds") or 300,
        timeout_seconds=timeout,
        max_rows=cfg.get("max_rows") or 500,
    )
    return Context(
        report_id, d, version, tables, columns, [],
        runner=runner, direct=spec,
    )


def _build_context(report_id: str, d: dict, version, integrations: dict,
                   schema_for, *, preview: bool = False) -> Context:
    if "direct" in d:
        return _build_direct_context(report_id, d, version)
    tables, columns, used = {}, {}, []
    for alias, ref in d["uses"].items():
        iid, name = ref.split(".", 1)
        integ = integrations.get(iid)
        if integ is None or name not in integ["definition"]["datasets"]:
            raise RenderError(
                render_errors.DATASET_MISSING, str(M("render.dataset_missing", dataset=ref)),
                status=409, report_id=report_id, dataset=ref, alias=alias,
            )
        tables[alias] = (schema_for(iid), name)
        columns[alias] = integ["definition"]["datasets"][name]["columns"]
        if iid not in used:
            used.append(iid)
    return Context(report_id, d, version, tables, columns, used, preview=preview)


def context(version: WorkspaceVersion, report_id: str) -> Context:
    rep = version.artifacts.get("reports", {}).get(report_id)
    if rep is None:
        raise ReportError(M("report.not_found"), 404, "not_found")
    return _build_context(report_id, rep["definition"], version,
                          version.artifacts.get("integrations", {}), datasets.schema_name)


_contexts: dict[tuple[int, str, str], Context] = {}
_contexts_lock = threading.Lock()


def cached_context(version, report_id: str) -> Context:
    """context() memoised per version and report: versions never change once applied, so the
    parsed definition and column contracts are built once per process."""
    key = (version.id, getattr(version, "checksum", None), report_id, datasets.schema_name("x"))
    with _contexts_lock:
        ctx = _contexts.get(key)
    if ctx is None:
        ctx = context(version, report_id)
        with _contexts_lock:
            if len(_contexts) > 256:
                _contexts.clear()
            _contexts[key] = ctx
    return ctx


def preview_context(version_like, report_id: str, report_def: dict, integrations: dict,
                    preview_iids: set[str], session_id: int) -> Context:
    """Draft integrations read from the session's preview schemas, others from published ones."""
    def schema_for(iid: str) -> str:
        if iid in preview_iids:
            with datasets.preview_schemas(datasets.preview_prefix(session_id)):
                return datasets.schema_name(iid)
        return datasets.schema_name(iid)

    return _build_context(report_id, report_def, version_like, integrations, schema_for,
                          preview=bool(preview_iids))


# --- SQL building --------------------------------------------------------------------------------

def expression(ctx: Context, text: str) -> sql.SQL:
    """A validated metric/dimension expression, regenerated with quoted identifiers."""
    problems = sqlsafety.check_expression(text, {a: set(c) for a, c in ctx.columns.items()})
    if problems:
        raise ReportError(
            M("report.unsafe_expression", detail=problems[0].message), 409, "unsafe_sql"
        )
    tree = sqlglot.parse_one(f"SELECT {text}", read="postgres").expressions[0]
    return sql.SQL(tree.sql(dialect="postgres", identify=True))


def _column(ctx: Context, ref: str) -> tuple[sql.Composed, dict]:
    alias, _, col = ref.partition(".")
    contract = ctx.columns.get(alias, {}).get(col)
    if contract is None:
        raise RenderError(
            render_errors.DATASET_MISSING,
            str(M("render.column_missing", column=col or ref, dataset=alias or ref)),
            status=409, report_id=ctx.report_id, dataset=alias or ref, column=col or ref,
        )
    return sql.SQL("{}.{}").format(sql.Identifier(alias), sql.Identifier(col)), contract


def date_expression(ctx: Context) -> sql.Composable:
    col, contract = _column(ctx, ctx.definition["date"])
    if contract["type"] == "timestamptz":
        # Session time zone = installation time zone (set per query).
        return sql.SQL("({})::date").format(col)
    return col


def _from(ctx: Context) -> sql.Composable:
    """FROM fragment: the rollup table when routed, else the full join chain."""
    if ctx.rollup is not None:
        r = ctx.rollup
        return sql.SQL("{}.{} AS r").format(sql.Identifier(r.schema), sql.Identifier(r.table))
    return from_clause(ctx)


def _date(ctx: Context) -> sql.Composable:
    if ctx.rollup is not None:
        return sql.SQL("{}.{}").format(sql.Identifier("r"), sql.Identifier("day"))
    return date_expression(ctx)


def _dim(ctx: Context, did: str) -> sql.Composable:
    if ctx.rollup is not None and did in ctx.rollup.dims:
        return sql.SQL("{}.{}").format(sql.Identifier("r"), sql.Identifier(f"k_{did}"))
    return expression(ctx, ctx.dimensions[did]["sql"])


def _metric(ctx: Context, mid: str) -> sql.Composable:
    if ctx.rollup is not None:
        return ctx.rollup.metrics[mid]
    return expression(ctx, ctx.metrics[mid]["sql"])


def from_clause(ctx: Context) -> sql.Composed:
    base = ctx.definition["date"].split(".", 1)[0]
    joined = {base}
    parts = [sql.SQL("{}.{} AS {}").format(sql.Identifier(ctx.tables[base][0]),
                                          sql.Identifier(ctx.tables[base][1]),
                                          sql.Identifier(base))]
    pending = list(ctx.definition.get("joins") or [])
    while pending:
        progressed = False
        for j in list(pending):
            left, right = j["left"].split(".")[0], j["right"].split(".")[0]
            if left in joined and right not in joined:
                new = right
            elif right in joined and left not in joined:
                new = left
            elif left in joined and right in joined:
                raise RenderError(
                    render_errors.JOIN_FAILED,
                    str(M("render.join_failed", sets=f"{left}, {right}",
                          on=f"{j['left']} = {j['right']}")),
                    status=409, report_id=ctx.report_id, sets=f"{left}, {right}",
                    key=f"{j['left']} = {j['right']}", reason="repeated",
                )
            else:
                continue
            kind = "LEFT JOIN" if (j.get("type") or "left") == "left" else "JOIN"
            parts.append(sql.SQL(kind + " {}.{} AS {} ON {} = {}").format(
                sql.Identifier(ctx.tables[new][0]), sql.Identifier(ctx.tables[new][1]),
                sql.Identifier(new), _column(ctx, j["left"])[0], _column(ctx, j["right"])[0]))
            joined.add(new)
            pending.remove(j)
            progressed = True
        if not progressed:
            sets = ", ".join(sorted({a for j in pending for a in
                                     (j["left"].split(".")[0], j["right"].split(".")[0])}))
            key = f"{pending[0]['left']} = {pending[0]['right']}"
            raise RenderError(
                render_errors.JOIN_FAILED,
                str(M("render.join_failed", sets=sets, on=key)),
                status=409, report_id=ctx.report_id, sets=sets, key=key,
                reason="disconnected",
            )
    missing = set(ctx.tables) - joined
    if missing:
        aliases = ", ".join(sorted(missing))
        raise RenderError(
            render_errors.JOIN_FAILED,
            str(M("render.join_failed", sets=aliases, on="—")),
            status=409, report_id=ctx.report_id, sets=aliases, reason="unjoined",
        )
    return sql.SQL(" ").join(parts)


def _where(ctx: Context, r: periods.Range, filters: dict[str, list[str]]) -> sql.Composed:
    parts = [sql.SQL("{} BETWEEN {} AND {}").format(_date(ctx), sql.Literal(r.start),
                                                   sql.Literal(r.end))]
    for dim, values in sorted(filters.items()):
        if not values:
            continue
        expr = _dim(ctx, dim)
        lits = sql.SQL(", ").join(sql.Literal(v) for v in values)
        parts.append(sql.SQL("({})::text IN ({})").format(expr, lits))
    return sql.SQL(" AND ").join(parts)


def sql_metrics(ctx: Context, metric_ids: list[str]) -> list[str]:
    """The SQL metrics needed for these metrics (formulas expanded), in a stable order."""
    need: list[str] = []
    for mid in metric_ids:
        m = ctx.metrics[mid]
        deps = [mid] if "sql" in m else sorted(formula_inputs(m["formula"]))
        for dep in deps:
            if dep not in need:
                need.append(dep)
    return need


def formula_inputs(formula: str) -> set[str]:
    tree = sqlglot.parse_one(f"SELECT {formula}", read="postgres").expressions[0]
    return {c.name for c in tree.find_all(exp.Column)}


def evaluate(ctx: Context, metric_id: str, values: dict[str, float | None]) -> float | None:
    m = ctx.metrics[metric_id]
    if "sql" in m:
        return values.get(metric_id)
    tree = sqlglot.parse_one(f"SELECT {m['formula']}", read="postgres").expressions[0]
    return _eval(tree, values)


def _eval(node: exp.Expression, values: dict) -> float | None:
    if isinstance(node, exp.Paren):
        return _eval(node.this, values)
    if isinstance(node, exp.Literal):
        return float(node.this)
    if isinstance(node, exp.Column):
        v = values.get(node.name)
        return None if v is None else float(v)
    if isinstance(node, exp.Neg):
        v = _eval(node.this, values)
        return None if v is None else -v
    if isinstance(node, exp.Add | exp.Sub | exp.Mul | exp.Div):
        a, b = _eval(node.left, values), _eval(node.right, values)
        if a is None or b is None:
            return None
        if isinstance(node, exp.Add):
            return a + b
        if isinstance(node, exp.Sub):
            return a - b
        if isinstance(node, exp.Mul):
            return a * b
        return None if b == 0 else a / b
    raise ReportError(M("report.unsupported_formula"), 409, "unsafe_sql")


def _number(v) -> float | None:
    if v is None:
        return None
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _query_failure(ctx: Context, exc: Exception, metric_ids: list[str]) -> RenderError | None:
    """A database failure while reading a report, as the code that names the piece at fault.

    Only identifiers and fixed reason tokens travel (constitution VIII): psycopg's text can quote
    the value that broke a cast, so `str(exc)` never reaches a message.
    """
    diag = getattr(exc, "diag", None)
    table = getattr(diag, "table_name", None) or None
    column = getattr(diag, "column_name", None) or None
    refs = ", ".join(sorted(ctx.definition.get("uses", {}).values()))
    if isinstance(exc, pg_errors.InvalidSchemaName | pg_errors.UndefinedTable):
        if ctx.preview:
            return RenderError(render_errors.PREVIEW_EXPIRED,
                               str(M("render.preview_expired")), status=409,
                               report_id=ctx.report_id, dataset=table)
        name = table or refs
        return RenderError(render_errors.DATASET_MISSING,
                           str(M("render.dataset_missing", dataset=name)), status=409,
                           report_id=ctx.report_id, dataset=name)
    if isinstance(exc, pg_errors.UndefinedColumn):
        return RenderError(render_errors.DATASET_MISSING,
                           str(M("render.column_missing", column=column or "?",
                                 dataset=refs)), status=409, report_id=ctx.report_id,
                           dataset=refs, column=column)
    if isinstance(exc, pg_errors.AmbiguousColumn):
        joins = ctx.definition.get("joins") or []
        key = f"{joins[0]['left']} = {joins[0]['right']}" if joins else "—"
        sets = ", ".join(sorted({a for j in joins for a in
                                 (j["left"].split(".")[0], j["right"].split(".")[0])})) or refs
        return RenderError(render_errors.JOIN_FAILED,
                           str(M("render.join_failed", sets=sets, on=key)), status=409,
                           report_id=ctx.report_id, sets=sets, key=key, reason="ambiguous")
    reason = None
    if isinstance(exc, pg_errors.DivisionByZero):
        reason = "division_by_zero"
    elif isinstance(exc, pg_errors.NumericValueOutOfRange):
        reason = "numeric_overflow"
    elif isinstance(exc, pg_errors.DataError):
        reason = "invalid_value"
    elif isinstance(exc, pg_errors.ProgrammingError):
        reason = "invalid_expression"
    if reason is None:
        return None
    metrics = ", ".join(metric_ids) or "?"
    return RenderError(render_errors.METRIC_ERROR,
                       str(M("render.metric_error", metric=metrics, reason=reason)),
                       report_id=ctx.report_id, metric=metrics, reason=reason)


def _query(statement: sql.Composed, tz: str) -> list[tuple]:
    """Read-only transaction with a time limit, sent with its query as one batch: a single round
    trip (the product database may be remote, ~200 ms each)."""
    with get_engine().connect() as conn:
        pg = conn.connection.driver_connection
        pg.autocommit = True   # the batch carries its own BEGIN ... COMMIT
        try:
            cur = pg.execute(sql.SQL(
                "BEGIN READ ONLY; SET LOCAL statement_timeout = {}; SET LOCAL TimeZone = {}; "
                "{}; COMMIT").format(
                sql.Literal(STATEMENT_TIMEOUT_MS), sql.Literal(tz), statement))
            while cur.description is None:   # skip BEGIN/SET results up to the query's rows
                if not cur.nextset():
                    raise ReportError(M("report.no_rows"), 500, "internal")
            return cur.fetchall()
        finally:
            if pg.info.transaction_status != pq.TransactionStatus.IDLE:
                pg.execute("ROLLBACK")   # failed mid-batch: leave the pooled connection clean
            pg.autocommit = False


def aggregate(ctx: Context, metric_ids: list[str], r: periods.Range, filters: dict, tz: str, *,
              group: list[tuple[str, sql.Composable]] | None = None,
              order_metric: str | None = None, limit: int | None = None,
              keys: list | None = None, session=None) -> list[dict]:
    """Rows of {group names..., metric ids...} (formulas computed)."""
    need = sql_metrics(ctx, metric_ids)
    group = group or []
    select_parts = [sql.SQL("{} AS {}").format(e, sql.Identifier(f"g{i}"))
                    for i, (_, e) in enumerate(group)]
    select_parts += [sql.SQL("{} AS {}").format(_metric(ctx, m),
                                                sql.Identifier(f"m_{m}")) for m in need]
    where = _where(ctx, r, filters)
    if keys is not None and group:
        where = sql.SQL("{} AND ({})::text = ANY({})").format(
            where, group[0][1], sql.Literal([str(k) for k in keys]))
    stmt = sql.SQL("SELECT {} FROM {} WHERE {}").format(
        sql.SQL(", ").join(select_parts), _from(ctx), where)
    if group:
        stmt += sql.SQL(" GROUP BY {}").format(
            sql.SQL(", ").join(sql.SQL(str(i + 1)) for i in range(len(group))))
    if order_metric and group:
        if "sql" in ctx.metrics[order_metric]:
            stmt += sql.SQL(" ORDER BY {} DESC NULLS LAST, 1").format(
                sql.Identifier(f"m_{order_metric}"))
        else:
            stmt += sql.SQL(" ORDER BY 1")
    if limit and (not order_metric or "sql" in ctx.metrics[order_metric]):
        stmt += sql.SQL(" LIMIT {}").format(sql.Literal(limit))
    try:
        if session is not None:
            result_rows = session.query(stmt, tz)
        else:
            with ctx.runner.session() as s:
                result_rows = s.query(stmt, tz)
    except pg_errors.Error as exc:
        error = _query_failure(ctx, exc, metric_ids)
        if error is None:
            raise
        raise error from None
    out = []
    for row in result_rows:
        values = {m: _number(v) for m, v in zip(need, row[len(group):], strict=True)}
        item = {name: row[i] for i, (name, _) in enumerate(group)}
        for mid in metric_ids:
            item[mid] = evaluate(ctx, mid, values)
        out.append(item)
    if order_metric and group and "sql" not in ctx.metrics[order_metric]:
        out.sort(key=lambda x: (x[order_metric] is None, -(x[order_metric] or 0)))
        out = out[:limit] if limit else out
    return out


