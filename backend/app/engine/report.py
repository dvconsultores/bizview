def _filter_options(ctx: Context, dim: str, sel: periods.Selection, tz: str,
                    q: str | None = None, limit: int | None = None, *,
                    session=None) -> tuple[list[str], bool]:
    limit = limit or FILTER_OPTIONS_LIMIT
    e = _dim(ctx, dim)
    where = _where(ctx, sel.current, {})
    q = (q or "").strip()[:200]
    if q:
        escaped = q.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        pattern = sql.Literal(f"%{escaped}%")
        where = sql.SQL("{} AND ({})::text ILIKE {} ESCAPE {}").format(
            where, e, pattern, sql.Literal("\\"))
    stmt = sql.SQL("SELECT DISTINCT ({})::text FROM {} WHERE {} ORDER BY 1 LIMIT {}").format(
        e, _from(ctx), where, sql.Literal(limit + 1))
    if session is not None:
        rows = [r[0] for r in session.query(stmt, tz) if r[0] is not None]
    else:
        with ctx.runner.session() as s:
            rows = [r[0] for r in s.query(stmt, tz) if r[0] is not None]
    return rows[:limit], len(rows) > limit


def filter_options(ctx: Context, dim: str, sel: periods.Selection, tz: str,
                   q: str | None = None, limit: int | None = None, *,
                   session=None) -> tuple[list[str], bool]:
    return _raw_on_missing(
        ctx, lambda c: _filter_options(c, dim, sel, tz, q, limit, session=session))


_route_defs: dict[tuple[int, object, str, str], object] = {}
_route_defs_lock = threading.Lock()


def _route_definition(ctx: Context):
    """Memoised rollup Definition per (version id, checksum, report id, schema prefix)."""
    from app.engine import rollup
    key = (ctx.version.id, getattr(ctx.version, "checksum", None), ctx.report_id,
           datasets.schema_name("x"))
    with _route_defs_lock:
        d = _route_defs.get(key)
    if d is None:
        d = rollup.definition(ctx.report_id, ctx.definition,
                              ctx.version.artifacts["integrations"])
        with _route_defs_lock:
            if len(_route_defs) > 256:
                _route_defs.clear()
            _route_defs[key] = d
    return d


def routed(db, ctx: Context) -> Context:
    """Route materialized daily reports to their fresh rollup; else return ctx unchanged."""
    if ctx.direct is not None or isinstance(ctx.version, PreviewVersion) \
            or ctx.version.id is None:
        return ctx
    from app.engine import rollup
    if not rollup.is_materialized(ctx.definition):
        return ctx
    try:
        d = _route_definition(ctx)
    except (rollup.RollupError, ReportError):
        return ctx
    row = db.execute(text(
        "SELECT rr.status, rr.definition_hash, rr.schema_name, rr.table_name, "
        "       rr.source_runs, rr.columns "
        "FROM report_rollup rr WHERE rr.report_id = :rid"), {"rid": ctx.report_id}).first()
    if row is None or row.status != "ready" or row.definition_hash != d.hash:
        return ctx
    keys = list(ctx.integrations) or [d.base_integration]
    runs = db.execute(text(
        "SELECT integration_id, max(id) FROM integration_run "
        "WHERE status = 'succeeded' AND integration_id = ANY(:ids) GROUP BY 1"),
        {"ids": keys}).all()
    got = {iid: rid for iid, rid in runs if rid is not None}
    src = row.source_runs or {}
    if set((src or {}).keys()) != set(got.keys()) or any(src[k] != got[k] for k in got):
        return ctx
    route = Route(row.schema_name, row.table_name,
                  {mid: rollup.metric_sql(d, mid, row.columns or {}) for mid in d.metrics},
                  frozenset(d.dimensions))
    return replace(ctx, rollup=route)


def _raw_on_missing(ctx: Context, fn):
    """Run fn(ctx); if the rollup is missing, mark it stale and retry on the raw path."""
    try:
        return fn(ctx)
    except (pg_errors.UndefinedTable, pg_errors.UndefinedColumn, RenderError) as exc:
        if isinstance(exc, RenderError) and exc.code not in (
                render_errors.DATASET_MISSING, render_errors.PREVIEW_EXPIRED):
            raise
        if ctx.rollup is None:
            raise
        from app.engine import rollup
        try:
            d = _route_definition(ctx)
            with get_engine().begin() as conn:
                rollup.mark_status(conn.connection.driver_connection, d, "stale",
                                   "falta la tabla o una columna del resumen diario")
        except (rollup.RollupError, ReportError, Exception):
            pass
        return fn(replace(ctx, rollup=None))


def render_reference() -> str:
    """Short reference that ties one payload's error cards to its lines in the server log."""
    return uuid.uuid4().hex[:12]


def _failed_view(ctx: Context, vdef: dict, error: RenderError, reference: str | None) -> dict:
    """A view that could not be built: its own error card, the rest of the dashboard unaffected."""
